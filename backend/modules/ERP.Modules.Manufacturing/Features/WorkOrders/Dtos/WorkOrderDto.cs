using ERP.Modules.Manufacturing.Domain;

namespace ERP.Modules.Manufacturing.Features;

public record WorkOrderOperationDto(
    Guid Id,
    Guid WorkOrderId,
    int SequenceOrder,
    string OperationName,
    string WorkCenterName,
    decimal PlannedHours,
    decimal ActualHours,
    decimal HourlyRate,
    OperationStatus Status);

public record WorkOrderMaterialIssueDto(
    Guid Id,
    Guid ItemId,
    string ItemCode,
    string ItemName,
    decimal Quantity,
    decimal UnitCost,
    decimal Value,
    DateOnly IssueDate,
    bool Backflushed,
    string? Notes,
    DateTimeOffset? ReversedAt);

public record WorkOrderDto(
    Guid Id,
    Guid LegalEntityId,
    string WorkOrderNumber,
    Guid BomId,
    string BomCode,
    Guid ProducedItemId,
    string ProducedItemCode,
    string ProducedItemName,
    decimal PlannedQuantity,
    decimal CompletedQuantity,
    decimal ScrappedQuantity,
    string Uom,
    Guid WarehouseId,
    DateOnly StartDate,
    DateOnly DueDate,
    DateOnly? CompletionDate,
    WorkOrderStatus Status,
    decimal EstimatedTotalCost,
    decimal ActualTotalCost,
    string? Notes,
    List<WorkOrderOperationDto> Operations,
    string? CustomFields,
    DateTimeOffset CreatedAt,
    decimal MaterialCost = 0,
    decimal ConversionCost = 0,
    decimal ScrapCost = 0,
    List<WorkOrderMaterialIssueDto>? MaterialIssues = null,
    DateTimeOffset? ReversedAt = null,
    Guid? ReversedByUserId = null,
    string? ReversalReason = null)
{
    public static WorkOrderDto From(WorkOrder w) => new(
        w.Id,
        w.LegalEntityId,
        w.WorkOrderNumber,
        w.BomId,
        w.BomCode,
        w.ProducedItemId,
        w.ProducedItemCode,
        w.ProducedItemName,
        w.PlannedQuantity,
        w.CompletedQuantity,
        w.ScrappedQuantity,
        w.Uom,
        w.WarehouseId,
        w.StartDate,
        w.DueDate,
        w.CompletionDate,
        w.Status,
        w.EstimatedTotalCost,
        w.ActualTotalCost,
        w.Notes,
        w.Operations.OrderBy(o => o.SequenceOrder).Select(o => new WorkOrderOperationDto(
            o.Id,
            o.WorkOrderId,
            o.SequenceOrder,
            o.OperationName,
            o.WorkCenterName,
            o.PlannedHours,
            o.ActualHours,
            o.HourlyRate,
            o.Status)).ToList(),
        w.CustomFields,
        w.CreatedAt,
        w.MaterialCost,
        w.ConversionCost,
        w.ScrapCost,
        w.MaterialIssues.OrderBy(i => i.IssueDate).ThenBy(i => i.CreatedAt).Select(i => new WorkOrderMaterialIssueDto(
            i.Id, i.ItemId, i.ItemCode, i.ItemName, i.Quantity, i.UnitCost, i.Value, i.IssueDate, i.Backflushed, i.Notes, i.ReversedAt)).ToList(),
        w.ReversedAt,
        w.ReversedByUserId,
        w.ReversalReason);
}
